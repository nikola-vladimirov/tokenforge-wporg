/* TokenForge: CSS hot reload (admins only).
 *
 * When the stylesheet is regenerated (Save / Regenerate / import in the
 * dashboard, wp-admin or the in-builder window), every open tab picks up the
 * new CSS without a page reload:
 *   front:  front end and the Bricks canvas: swap <link id="tokenforge-css">
 *             (new link loads first, then the old one is removed) or replace
 *             the inline <style id="tokenforge-inline-css">; the same for the
 *             WooCommerce shop pages sheet (tokenforge-shop) when the page has it.
 *   editor: Gutenberg: replace TokenForge's entry in the block-editor
 *             content styles, so the editor canvas restyles itself.
 * Signals: a BroadcastChannel message from the dashboard (instant, same
 * browser) plus a light version check while the tab is visible (catches saves
 * from another browser/device).
 */
( function () {
	'use strict';
	if ( window.__tokenforgeHot ) { return; }
	window.__tokenforgeHot = true;

	var cfg = window.TokenForgeHot || {};
	var ver = String( cfg.ver || '' );
	var busy = false, pending = null, polling = true;

	function bust( url, v ) { return url.replace( /([?&])ver=[^&]*/, '$1ver=' + encodeURIComponent( v ) ); }

	function toast() {
		if ( window.top !== window || 'editor' === cfg.mode ) { return; } // not inside the Bricks canvas
		var t = document.createElement( 'div' );
		t.textContent = 'TokenForge CSS updated';
		t.setAttribute( 'style', 'position:fixed;left:16px;bottom:16px;z-index:2147483000;padding:7px 12px;border-radius:16px;background:#161d2b;color:#e7eaf0;font:600 12px/1.2 system-ui,sans-serif;box-shadow:0 4px 16px rgba(0,0,0,.35);opacity:0;transition:opacity .2s' );
		document.body.appendChild( t );
		requestAnimationFrame( function () { t.style.opacity = '1'; } );
		setTimeout( function () { t.style.opacity = '0'; setTimeout( function () { t.remove(); }, 250 ); }, 1400 );
	}

	function fetchText( url ) {
		return fetch( url, { cache: 'no-store', credentials: 'same-origin' } ).then( function ( r ) {
			if ( ! r.ok ) { throw new Error( 'HTTP ' + r.status ); }
			return r.text();
		} );
	}

	function api( path ) {
		return fetch( cfg.restUrl + path, { credentials: 'same-origin', cache: 'no-store', headers: { 'X-WP-Nonce': cfg.nonce } } ).then( function ( r ) {
			if ( 401 === r.status || 403 === r.status ) { polling = false; } // nonce expired / logged out
			if ( ! r.ok ) { throw new Error( 'HTTP ' + r.status ); }
			return r.json();
		} );
	}

	// ---- Appliers ----
	function applyFront( url ) {
		var link = document.getElementById( 'tokenforge-css' );
		// The builder canvas has the file with every utility class: stay on it.
		if ( link && /\/tokenforge-full\.css/.test( link.href ) ) { url = url.replace( /\/tokenforge\.css/, '/tokenforge-full.css' ); }
		if ( link ) {
			return new Promise( function ( resolve, reject ) {
				var next = link.cloneNode();
				next.id = 'tokenforge-css-next';
				next.href = url;
				next.onload = function () { link.remove(); next.id = 'tokenforge-css'; resolve(); };
				next.onerror = function () { next.remove(); reject( new Error( 'load failed' ) ); };
				link.parentNode.insertBefore( next, link.nextSibling );
			} );
		}
		var style = document.getElementById( 'tokenforge-inline-css' );
		if ( style ) {
			return fetchText( url ).then( function ( css ) { style.textContent = css; } );
		}
		return Promise.reject( new Error( 'no TokenForge stylesheet on this page' ) );
	}

	// The WooCommerce shop pages sheet (only on pages that show the shop).
	function applyShop( v ) {
		if ( ! cfg.shopUrl ) { return Promise.resolve(); }
		var url = bust( cfg.shopUrl, v );
		var link = document.getElementById( 'tokenforge-shop-css' );
		if ( link ) {
			return new Promise( function ( resolve ) {
				var next = link.cloneNode();
				next.id = 'tokenforge-shop-css-next';
				next.href = url;
				next.onload = function () { link.remove(); next.id = 'tokenforge-shop-css'; resolve(); };
				next.onerror = function () { next.remove(); link.disabled = true; resolve(); }; // switched off: the file is gone
				link.parentNode.insertBefore( next, link.nextSibling );
			} );
		}
		var style = document.getElementById( 'tokenforge-shop-inline-css' );
		if ( style ) {
			return fetchText( url ).then( function ( css ) { style.textContent = css; }, function () { style.textContent = ''; } );
		}
		return Promise.resolve();
	}

	function applyEditor() {
		var wp = window.wp;
		if ( ! wp || ! wp.data || ! wp.data.select( 'core/block-editor' ) ) { return Promise.reject( new Error( 'no block editor' ) ); }
		return api( '/editor-css' ).then( function ( res ) {
			var swap = function ( list ) {
				var styles = ( list || [] ).slice(), i = -1;
				styles.forEach( function ( s, idx ) { if ( s && typeof s.css === 'string' && s.css.indexOf( 'Generated by TokenForge' ) > -1 ) { i = idx; } } );
				if ( i > -1 ) { styles[ i ] = Object.assign( {}, styles[ i ], { css: res.css } ); } else { styles.push( { css: res.css } ); }
				return styles;
			};
			// The post editor renders its canvas from the core/editor settings
			// (and syncs them down to core/block-editor), so update those first.
			var editor = wp.data.select( 'core/editor' );
			if ( editor && editor.getEditorSettings && wp.data.dispatch( 'core/editor' ).updateEditorSettings ) {
				wp.data.dispatch( 'core/editor' ).updateEditorSettings( { styles: swap( editor.getEditorSettings().styles ) } );
				return;
			}
			wp.data.dispatch( 'core/block-editor' ).updateSettings( { styles: swap( wp.data.select( 'core/block-editor' ).getSettings().styles ) } );
		} );
	}

	function update( nextVer, url ) {
		nextVer = String( nextVer || '' );
		if ( ! nextVer || nextVer === ver ) { return; }
		if ( busy ) { pending = [ nextVer, url ]; return; }
		busy = true;
		var job = 'editor' === cfg.mode ? applyEditor() : applyFront( url || bust( cfg.url || '', nextVer ) ).then( function () { return applyShop( nextVer ); } );
		job.then( function () { ver = nextVer; toast(); }, function () {} ).then( function () {
			busy = false;
			if ( pending ) { var p = pending; pending = null; update( p[0], p[1] ); }
		} );
	}

	// ---- Signals ----
	function onMessage( data ) {
		if ( data && 'tokenforge:css' === data.type ) { update( data.ver, data.url ); }
	}
	if ( typeof window.BroadcastChannel === 'function' ) {
		try { new window.BroadcastChannel( 'tokenforge' ).onmessage = function ( e ) { onMessage( e.data ); }; } catch ( e ) {}
	}
	window.addEventListener( 'tokenforge:css', function ( e ) { onMessage( e.detail ); } );

	function check() {
		if ( ! polling || document.visibilityState !== 'visible' ) { return; }
		api( '/css-version' ).then( function ( res ) { update( res.ver, res.url ); }, function () {} );
	}
	var every = Math.max( 2000, parseInt( cfg.interval, 10 ) || 5000 );
	setInterval( check, every );
	document.addEventListener( 'visibilitychange', check );
} )();
